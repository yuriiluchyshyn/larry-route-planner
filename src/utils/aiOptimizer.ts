/**
 * Call Groq API for route optimization (FREE!)
 */
async function callGroq(prompt: string): Promise<string> {
  const apiKey = getGroqKey();
  if (!apiKey) {
    throw new Error('Groq API key не знайдено. Додайте GROQ_API_KEY в localStorage.');
  }

  console.log('🤖 Larry AI: Calling Groq API (FREE)...');
  
  const response = await fetch(AI_CONFIG.GROQ_URL, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Authorization': `Bearer ${apiKey}`
    },
    body: JSON.stringify({
      model: AI_CONFIG.GROQ_MODEL,
      messages: [{
        role: 'user',
        content: prompt + '\n\nВідповідь надайте ТІЛЬКИ у форматі JSON без додаткового тексту:'
      }],
      max_tokens: AI_CONFIG.MAX_TOKENS,
      temperature: AI_CONFIG.TEMPERATURE,
    })
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const errorMsg = errorData.error?.message || '';
    
    // Check for context length exceeded
    if (response.status === 400 && (errorMsg.includes('context_length') || errorMsg.includes('too long') || errorMsg.includes('maximum') || errorMsg.includes('reduce the length'))) {
      throw new Error(`CONTEXT_TOO_LONG: Промпт занадто великий для Groq. Автоматично зменшую кількість пропозицій...`);
    }
    
    // Check for token limit exceeded (TPM - tokens per minute)
    if (response.status === 429 && (errorMsg.includes('rate_limit_exceeded') || errorMsg.includes('Request too large') || errorMsg.includes('TPM'))) {
      throw new Error(`CONTEXT_TOO_LONG: Перевищено ліміт токенів Groq. Автоматично зменшую кількість пропозицій...`);
    }
    
    throw new Error(`Groq API error: ${response.status} ${response.statusText}. ${errorMsg}`);
  }

  const data = await response.json();
  
  if (!data.choices || !data.choices[0] || !data.choices[0].message) {
    throw new Error('Неправильна відповідь від Groq API');
  }

  return data.choices[0].message.content;
}

