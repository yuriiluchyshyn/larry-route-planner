/**
 * Extract JSON from AI response text that may contain extra text around it
 */
function extractJSON(text: string): string {
  // Step 1: Try to parse as-is
  const trimmed = text.trim();
  try {
    JSON.parse(trimmed);
    return trimmed;
  } catch { /* continue */ }

  // Step 2: Remove markdown code blocks
  const withoutMarkdown = trimmed.replace(/```json\n?/g, '').replace(/```\n?/g, '').trim();
  try {
    JSON.parse(withoutMarkdown);
    return withoutMarkdown;
  } catch { /* continue */ }

  // Step 3: Find JSON object by matching first { to last }
  const firstBrace = text.indexOf('{');
  const lastBrace = text.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace !== -1 && lastBrace > firstBrace) {
    const jsonCandidate = text.substring(firstBrace, lastBrace + 1);
    try {
      JSON.parse(jsonCandidate);
      return jsonCandidate;
    } catch { /* continue */ }
  }

  // Step 4: Try to find JSON array
  const firstBracket = text.indexOf('[');
  const lastBracket = text.lastIndexOf(']');
  if (firstBracket !== -1 && lastBracket !== -1 && lastBracket > firstBracket) {
    // Wrap in object if it's just an array
    const arrayCandidate = text.substring(firstBracket, lastBracket + 1);
    try {
      const parsed = JSON.parse(arrayCandidate);
      if (Array.isArray(parsed)) {
        return JSON.stringify({ routes: parsed, reasoning: '', confidence: 0.7 });
      }
    } catch { /* continue */ }
  }

  // Step 5: Failed - throw with context
  throw new Error(`"${text.substring(0, 100)}..." is not valid JSON`);
}

