/**
 * Parse AI response and convert to OptimizedRoute format
 */
function parseAIResponse(
  aiResponseText: string,
  offers: FreightOffer[], 
  config: AIOptimizerConfig
): OptimizedRoute[] {
  console.log('🤖 Larry AI: Parsing AI response...');
  console.log('🤖 Larry AI: Response text length:', aiResponseText.length);
  console.log('🤖 Larry AI: Response preview:', aiResponseText.substring(0, 200));
  
  // Check if response is empty or too short
  if (!aiResponseText || aiResponseText.trim().length < 10) {
    throw new Error('AI повернув порожню або занадто коротку відповідь');
  }
  
  let parsedResponse: AIAPIResponse;
  try {
    const jsonStr = extractJSON(aiResponseText);
    console.log('🤖 Larry AI: Extracted JSON length:', jsonStr.length);
    parsedResponse = JSON.parse(jsonStr);
  } catch (parseError) {
    console.error('🤖 Larry AI: Failed to parse AI response:', aiResponseText.substring(0, 500));
    throw new Error(`Не вдалося розпарсити відповідь AI: ${parseError instanceof Error ? parseError.message : 'Невідома помилка'}`);
  }

  if (!parsedResponse.routes || !Array.isArray(parsedResponse.routes)) {
    console.error('🤖 Larry AI: Invalid response structure:', parsedResponse);
    throw new Error('AI відповідь не містить валідних маршрутів');
  }

  if (parsedResponse.routes.length === 0) {
    console.warn('🤖 Larry AI: AI returned empty routes array');
    throw new Error('AI не знайшов жодного підходящого маршруту');
  }

  const routes: OptimizedRoute[] = [];
  const offerMap = new Map(offers.map(o => [o.id, o]));
  
  console.log(`🤖 Larry AI: Processing ${parsedResponse.routes.length} routes from AI`);
  
  let processedCount = 0;
  let skippedCount = 0;
  
  for (const aiRoute of parsedResponse.routes) {
    try {
      // Validate AI route data
      if (!aiRoute.offerIds || !Array.isArray(aiRoute.offerIds)) {
        console.warn('🤖 Larry AI: Skipping route with invalid offerIds:', aiRoute);
        continue;
      }

      // Find offers for this route
      const routeOffers: FreightOffer[] = [];
      for (const offerId of aiRoute.offerIds) {
        const offer = offerMap.get(offerId);
        if (offer) {
          routeOffers.push(offer);
        } else {
          console.warn(`🤖 Larry AI: Offer ${offerId} not found in available offers`);
        }
      }

      if (routeOffers.length === 0) {
        console.warn('🤖 Larry AI: Skipping route with no valid offers');
        continue;
      }

      // Create route segments
      const segments: RouteSegment[] = routeOffers.map((offer, idx) => {
        const loadingSpot = offer.freight.spots.find(s => 
          s.operations.some(o => o.type === 'loading')
        );
        const unloadingSpot = offer.freight.spots.find(s => 
          s.operations.some(o => o.type === 'unloading')
        );
        
        const loadingDate = loadingSpot?.operations.find(o => o.type === 'loading')?.timespan.begin || new Date().toISOString();
        const unloadingDate = unloadingSpot?.operations.find(o => o.type === 'unloading')?.timespan.begin || new Date().toISOString();
        
        const distanceKm = (offer.freight.route.distance || 0) / 1000;
        const pricePerKm = offer.price.value && distanceKm > 0 ? offer.price.value / distanceKm : null;
        
        // Calculate empty distance (simplified - in real implementation would use routing API)
        let emptyDistanceKm = 0;
        if (idx === 0) {
          // Distance from home base to first loading point
          const loadingCoords = loadingSpot?.place.coordinates;
          if (loadingCoords) {
            emptyDistanceKm = calculateDistance(
              config.homeBaseLat, config.homeBaseLon,
              loadingCoords.latitude, loadingCoords.longitude
            );
          }
        } else {
          // Distance from previous unloading to current loading
          const prevOffer = routeOffers[idx - 1];
          const prevUnloadingSpot = prevOffer.freight.spots.find(s => 
            s.operations.some(o => o.type === 'unloading')
          );
          const currentLoadingSpot = loadingSpot;
          
          if (prevUnloadingSpot && currentLoadingSpot) {
            emptyDistanceKm = calculateDistance(
              prevUnloadingSpot.place.coordinates.latitude,
              prevUnloadingSpot.place.coordinates.longitude,
              currentLoadingSpot.place.coordinates.latitude,
              currentLoadingSpot.place.coordinates.longitude
            );
          }
        }
        
        return {
          offer,
          from: loadingSpot?.place.address.locality || 'Unknown',
          to: unloadingSpot?.place.address.locality || 'Unknown',
          distanceKm,
          loadingDate,
          unloadingDate,
          pricePerKm,
          isEmpty: false,
          emptyDistanceKm,
          drivingHours: distanceKm / config.averageSpeedKmh, // Use configured average speed
          restStops: Math.ceil(distanceKm / (4.5 * config.averageSpeedKmh)), // Break every 4.5h * speed km/h
        };
      });

      // Calculate return distance to home base
      const lastOffer = routeOffers[routeOffers.length - 1];
      const lastUnloadingSpot = lastOffer.freight.spots.find(s => 
        s.operations.some(o => o.type === 'unloading')
      );
      let returnDistanceKm = 0;
      if (lastUnloadingSpot) {
        returnDistanceKm = calculateDistance(
          lastUnloadingSpot.place.coordinates.latitude,
          lastUnloadingSpot.place.coordinates.longitude,
          config.homeBaseLat,
          config.homeBaseLon
        );
      }

      // Use AI provided values or calculate from segments
      // IMPORTANT: Use !== undefined check because 0 is a valid value
      const totalLoaded = aiRoute.loadedDistanceKm !== undefined ? aiRoute.loadedDistanceKm : segments.reduce((sum, s) => sum + s.distanceKm, 0);
      
      // Calculate empty distance ourselves (more accurate than AI which sometimes miscalculates)
      const calculatedEmpty = segments.reduce((sum, s) => sum + s.emptyDistanceKm, 0) + returnDistanceKm;
      const aiEmpty = aiRoute.emptyDistanceKm !== undefined ? aiRoute.emptyDistanceKm : calculatedEmpty;
      
      // Use the LARGER of AI's value vs our calculation (AI sometimes underestimates)
      const totalEmpty = Math.max(aiEmpty, calculatedEmpty);
      
      const totalDistance = totalLoaded + totalEmpty;
      const emptyPercent = totalDistance > 0 ? (totalEmpty / totalDistance) * 100 : 0;
      const totalDriving = aiRoute.totalDrivingHours !== undefined ? aiRoute.totalDrivingHours : (segments.reduce((sum, s) => sum + s.drivingHours, 0) + (returnDistanceKm / config.averageSpeedKmh));
      
      // Log info but DON'T filter — user decides what routes to use
      if (emptyPercent > config.maxEmptyRunPercent) {
        console.info(`🤖 Larry AI: Route has ${emptyPercent.toFixed(1)}% empty run (target: <${config.maxEmptyRunPercent}%)`);
      }
      if (segments.length < 2) {
        console.info(`🤖 Larry AI: Single-offer route (${segments.length} offers)`);
      }

      processedCount++;

      const optimizedRoute: OptimizedRoute = {
        segments,
        totalDistanceKm: totalDistance,
        loadedDistanceKm: totalLoaded,
        emptyDistanceKm: totalEmpty,
        emptyRunPercent: emptyPercent,
        totalDays: aiRoute.totalDays || Math.ceil(totalDriving / 9),
        idleHours: 0,
        totalDrivingHours: aiRoute.totalDrivingHours || totalDriving,
        totalRestHours: Math.ceil(totalDriving / 9) * 11,
        mandatoryBreaks: Math.ceil(totalDriving / 4.5),
        weeklyRestsNeeded: Math.ceil(Math.ceil(totalDriving / 9) / 6),
        score: aiRoute.score || 80,
        euCompliant: aiRoute.euCompliant !== undefined ? aiRoute.euCompliant : totalDriving <= 56,
        timeOverlap: aiRoute.timeOverlap || false,
      };

      routes.push(optimizedRoute);
      
    } catch (routeError) {
      console.error('🤖 Larry AI: Error processing route:', routeError, aiRoute);
      // Continue with other routes - don't increment counters for errors
    }
  }

  console.log(`🤖 Larry AI: Successfully parsed ${routes.length} routes from AI response (processed: ${processedCount})`);
  
  if (routes.length === 0) {
    throw new Error('Не вдалося створити жодного валідного маршруту з AI відповіді');
  }
  
  return routes;
}

/**
 * Calculate distance between two coordinates using Haversine formula (in km)
 */
function calculateDistance(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth's radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c * 1.3; // Add 30% for road distance vs straight line
}

