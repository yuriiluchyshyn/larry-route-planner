/**
 * Main AI optimization function
 */
export async function buildAIOptimizedRoutes(
  offers: FreightOffer[] | { mainOffers: FreightOffer[]; returnOffers: FreightOffer[] },
  config: AIOptimizerConfig,
  statusCallback?: (status: string) => void
): Promise<OptimizedRoute[]> {
  console.log('🤖 Larry AI: Starting AI-powered route optimization...');
  
  // Normalize input
  let mergedOffers: FreightOffer[];
  if (Array.isArray(offers)) {
    mergedOffers = offers;
  } else {
    const { mainOffers, returnOffers } = offers;
    const seen = new Set<string>();
    mergedOffers = [];
    
    for (const o of mainOffers) {
      if (!seen.has(o.id)) {
        seen.add(o.id);
        mergedOffers.push(o);
      }
    }
    for (const o of returnOffers) {
      if (!seen.has(o.id)) {
        seen.add(o.id);
        mergedOffers.push(o);
      }
    }
  }
  
  if (mergedOffers.length === 0) {
    console.log('🤖 Larry AI: No offers to optimize');
    return [];
  }
  
  console.log(`🤖 Larry AI: Optimizing ${mergedOffers.length} offers using real AI service`);
  
  // Step 1: Soft pre-filter — тільки відкидаємо пропозиції де завантаження ДО дати виїзду
  // Решту рішень приймає AI і позначає ризики
  const depFrom = new Date(config.departureFrom);
  
  const dateFilteredOffers = mergedOffers.filter(offer => {
    const loadingSpot = offer.freight.spots.find(s => 
      s.operations.some(o => o.type === 'loading')
    );
    
    const loadingDate = loadingSpot?.operations.find(o => o.type === 'loading')?.timespan.begin;
    
    // Тільки відкидаємо пропозиції де завантаження ДО дати виїзду (фізично неможливо)
    if (loadingDate) {
      const loadDate = new Date(loadingDate);
      if (loadDate < depFrom) return false;
    }
    
    return true;
  });
  
  if (dateFilteredOffers.length < mergedOffers.length) {
    const removed = mergedOffers.length - dateFilteredOffers.length;
    const message = `🗓️ Відфільтровано ${removed} пропозицій за датами (не вкладаються в ${config.departureFrom} — ${config.returnTo})`;
    console.log(`🤖 Larry AI: ${message}`);
    if (statusCallback) statusCallback(`🤖 ${message}`);
  }
  
  if (dateFilteredOffers.length === 0) {
    console.log('🤖 Larry AI: No offers match date range after filtering');
    return [];
  }
  
  // Step 2: Limit offers to fit within AI context window
  // Gemini 2.0 Flash: 1M context but rate limited on requests per minute
  // Each offer line is ~200 chars ≈ ~50 tokens
  // Keep prompt under ~30KB to avoid rate limits
  const MAX_OFFERS_FOR_AI = AI_LIMITS.MAX_OFFERS_FOR_AI;
  let offersForAI = dateFilteredOffers;
  let wasLimited = false;
  
  if (dateFilteredOffers.length > MAX_OFFERS_FOR_AI) {
    wasLimited = true;
    const message = `⚠️ Забагато пропозицій (${dateFilteredOffers.length}), обмежую до ${MAX_OFFERS_FOR_AI} найкращих`;
    console.log(`🤖 Larry AI: ${message}`);
    if (statusCallback) statusCallback(`🤖 ${message}...`);
    
    // Score and sort offers by relevance:
    // - Higher price per km = better
    // - Reasonable distance (not too short, not too long) = better  
    // - Closer to other offers (for chaining) = better
    offersForAI = [...dateFilteredOffers]
      .map(offer => {
        const loadingSpot = offer.freight.spots.find(s => 
          s.operations.some(o => o.type === 'loading')
        );
        const distKm = (offer.freight.route.distance || 0) / 1000;
        const pricePerKm = offer.price.value && distKm > 0 ? offer.price.value / distKm : 0;
        
        // Distance from home to loading point
        const loadLat = loadingSpot?.place.coordinates.latitude || 0;
        const loadLon = loadingSpot?.place.coordinates.longitude || 0;
        const distFromHome = Math.sqrt(
          Math.pow(loadLat - config.homeBaseLat, 2) + 
          Math.pow(loadLon - config.homeBaseLon, 2)
        ) * 111; // rough km conversion
        
        // Prefer routes that are:
        // 1. High price per km (most important)
        // 2. Good distance (300-800km sweet spot)
        // 3. Not too far from home base
        const distanceScore = distKm > 200 && distKm < 1000 ? 1.5 : 1.0; // Bonus for good distances
        const homeDistanceScore = distFromHome < 500 ? 1.2 : 1.0; // Bonus for reasonable home distance
        
        const score = pricePerKm * 100 * distanceScore * homeDistanceScore + distKm * 0.3;
        
        return { offer, score, pricePerKm, distKm, distFromHome };
      })
      .sort((a, b) => b.score - a.score)
      .slice(0, MAX_OFFERS_FOR_AI)
      .map(item => item.offer);
    
    console.log(`🤖 Larry AI: Selected top ${offersForAI.length} offers by relevance score`);
    if (statusCallback) statusCallback(`🤖 Відібрано ${offersForAI.length} найкращих пропозицій...`);
  }
  
  try {
    // Generate AI prompt
    const prompt = await generateAIPrompt(offersForAI, config);
    console.log(`🤖 Larry AI: Generated prompt (${prompt.length} characters, ${offersForAI.length} offers)`);
    
    // Save prompt to file for debugging
    savePromptToFile(prompt, config, offersForAI.length);
    
    if (wasLimited) {
      console.log(`🤖 Larry AI: ⚠️ Prompt was limited from ${mergedOffers.length} to ${offersForAI.length} offers to fit AI context window`);
    }
    console.log(`🤖 Larry AI: === PROMPT START ===\n${prompt}\n=== PROMPT END ===`);
    
    // Call real AI service
    let aiResponse;
    try {
      aiResponse = await callAIService(prompt);
    } catch (firstError) {
      // If context too long, retry with fewer offers
      if (firstError instanceof Error && firstError.message.includes('CONTEXT_TOO_LONG') && offersForAI.length > AI_LIMITS.MIN_OFFERS_FOR_RETRY) {
        const reducedCount = Math.floor(offersForAI.length * AI_LIMITS.RETRY_REDUCTION_PERCENT);
        const message = `⚠️ Контекст занадто великий, зменшую до ${reducedCount} пропозицій`;
        console.log(`🤖 Larry AI: ${message} (було ${offersForAI.length})`);
        if (statusCallback) statusCallback(`🤖 ${message}...`);
        
        const reducedOffers = offersForAI.slice(0, reducedCount);
        const reducedPrompt = await generateAIPrompt(reducedOffers, config);
        console.log(`🤖 Larry AI: Reduced prompt (${reducedPrompt.length} characters, ${reducedOffers.length} offers)`);
        
        // Save reduced prompt to file
        savePromptToFile(reducedPrompt, config, reducedOffers.length);
        
        try {
          aiResponse = await callAIService(reducedPrompt);
        } catch (secondError) {
          // If still too long, try with even fewer
          if (secondError instanceof Error && secondError.message.includes('CONTEXT_TOO_LONG') && reducedCount > 10) {
            const minCount = Math.min(AI_LIMITS.MIN_OFFERS_FOR_RETRY, Math.floor(reducedCount * 0.5));
            const finalMessage = `⚠️ Все ще занадто великий, зменшую до ${minCount} пропозицій`;
            console.log(`🤖 Larry AI: ${finalMessage}`);
            if (statusCallback) statusCallback(`🤖 ${finalMessage}...`);
            
            const minOffers = offersForAI.slice(0, minCount);
            const minPrompt = await generateAIPrompt(minOffers, config);
            
            // Save final reduced prompt to file
            savePromptToFile(minPrompt, config, minOffers.length);
            
            aiResponse = await callAIService(minPrompt);
          } else {
            throw secondError;
          }
        }
      } else {
        throw firstError;
      }
    }
    
    console.log('🤖 Larry AI: Received AI response, parsing...');
    
    // Save AI response to file for debugging
    saveResponseToFile(aiResponse.rawText, aiResponse.processingTime);
    
    // Parse and convert AI response to OptimizedRoute format
    const routes = parseAIResponse(aiResponse.rawText, mergedOffers, config);
    
    console.log(`🤖 Larry AI: Successfully generated ${routes.length} AI-optimized routes`);
    console.log(`🤖 Larry AI: Processing time: ${aiResponse.processingTime}ms`);
    console.log(`🤖 Larry AI: Confidence: ${(aiResponse.confidence * 100).toFixed(1)}%`);
    console.log(`🤖 Larry AI: AI Reasoning: ${aiResponse.reasoning}`);
    
    return routes;
    
  } catch (error) {
    console.error('🤖 Larry AI: Error during AI optimization:', error);
    
    // Show user-friendly error message
    const errorMessage = error instanceof Error ? error.message : 'Невідома помилка';
    
    // Throw error so App.tsx can display it properly
    console.error('🤖 Larry AI: Error:', errorMessage);
    throw new Error(`AI оптимізація не вдалася: ${errorMessage}`);
  }
}