/**
 * Call Google Gemini API for route optimization (FREE with high limits!)
 */
async function callGemini(prompt: string): Promise<string> {
  const apiKey = getGeminiKey();
  if (!apiKey) {
    throw new Error('Google Gemini API key не знайдено. Додайте GEMINI_API_KEY в localStorage.');
  }

  console.log('🤖 Larry AI: Calling Google Gemini API (FREE with 1M tokens/min)...');
  
  const response = await fetch(`${AI_CONFIG.GEMINI_URL}?key=${apiKey}`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json'
    },
    body: JSON.stringify({
      contents: [{
        parts: [{
          text: prompt + '\n\nВідповідь надайте ТІЛЬКИ у форматі JSON без додаткового тексту:'
        }]
      }],
      generationConfig: {
        temperature: AI_CONFIG.TEMPERATURE,
        maxOutputTokens: AI_CONFIG.MAX_TOKENS,
      }
    })
  });

  if (!response.ok) {
    const errorData = await response.json().catch(() => ({}));
    const errorMsg = errorData.error?.message || '';
    
    // Check for rate limit / quota exceeded (429)
    if (response.status === 429) {
      throw new Error(`CONTEXT_TOO_LONG: Перевищено ліміт запитів Gemini (429). Автоматично зменшую кількість пропозицій...`);
    }
    
    throw new Error(`Google Gemini API error: ${response.status} ${response.statusText}. ${errorMsg}`);
  }

  const data = await response.json();
  console.log('🤖 Larry AI: Gemini response data:', JSON.stringify(data, null, 2));
  
  // Check if response structure is valid
  if (!data.candidates || !data.candidates[0]) {
    throw new Error('Неправильна відповідь від Google Gemini API: відсутні candidates');
  }

  const candidate = data.candidates[0];
  
  // Check for MAX_TOKENS finish reason
  if (candidate.finishReason === 'MAX_TOKENS') {
    console.warn('🤖 Larry AI: Gemini response was truncated due to MAX_TOKENS limit');
    throw new Error(`CONTEXT_TOO_LONG: Відповідь Gemini обрізана через ліміт токенів (${AI_CONFIG.MAX_TOKENS}). Автоматично зменшую кількість пропозицій...`);
  }
  
  // Check for other problematic finish reasons
  if (candidate.finishReason && candidate.finishReason !== 'STOP') {
    console.warn('🤖 Larry AI: Gemini finished with reason:', candidate.finishReason);
    throw new Error(`Gemini API завершився з причиною: ${candidate.finishReason}`);
  }

  // Check if content exists and has parts
  if (!candidate.content || !candidate.content.parts || !candidate.content.parts[0]) {
    throw new Error('Неправильна відповідь від Google Gemini API: відсутній контент');
  }

  const responseText = candidate.content.parts[0].text;
  
  // Check if response is empty
  if (!responseText || responseText.trim().length === 0) {
    throw new Error('Gemini API повернув порожню відповідь');
  }

  console.log('🤖 Larry AI: Gemini response text length:', responseText.length);
  return responseText;
}
